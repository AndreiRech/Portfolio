export type SignId = (typeof SIGNS)[number]["id"];

const SIZE = 20;

/** Merges each row into horizontal runs so a sign is a few dozen rects. */
function runs(pixels: readonly string[]) {
  const top = Math.floor((SIZE - pixels.length) / 2);
  const rects: { x: number; y: number; width: number }[] = [];
  pixels.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== "#") continue;
      let end = x;
      while (row[end + 1] === "#") end++;
      rects.push({ x, y: y + top, width: end - x + 1 });
      x = end;
    }
  });
  return rects;
}

export default function SignGlyph({ id }: { id: string }) {
  const sign = SIGNS.find((sign) => sign.id === id) ?? SIGNS[0];
  return (
    <svg
      viewBox={`0 0 ${SIZE} ${SIZE}`}
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      {runs(sign.pixels).map((rect) => (
        <rect
          key={`${rect.x}-${rect.y}`}
          x={rect.x}
          y={rect.y}
          width={rect.width}
          height={1}
        />
      ))}
    </svg>
  );
}
