const onix = (() => {
  const c = new C(34, 36);
  // A chain of boulders curling up from the ground, the head on top.
  const rocks = [
    [5, 32, 3.6], [11, 32.6, 3.8], [17.5, 31.6, 4], [23.6, 28, 4.2],
    [26.5, 21.5, 4.3], [24.8, 15, 4.1], [20, 10.6, 3.8], [14.5, 8.3, 3.6],
  ];
  for (const [x, y, r] of rocks) c.disc(x, y, r);
  // Head with a brow horn.
  c.rect(4, 3, 9, 8).rect(3, 5, 2, 5).rect(2, 7, 1, 3);
  c.rect(8, 1, 3, 2).rect(9, 0, 2, 1);
  c.clear(6, 5, 1, 1);
  // Rock seams.
  for (const [x, y, r] of rocks.slice(1)) {
    void r;
    c.set(Math.round(x - 0.5), Math.round(y - 3.5), false);
  }
  return c.rows();
})();

